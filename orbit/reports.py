"""Render human-readable performance reports from synced metrics.

The Threads Growth skill (SKILL.md) promises a `references/winning-formats.md`
file kept in sync with real performance data. This module writes it.
"""
from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from orbit.db import DB


def find_repo_root(start: Path | None = None) -> Path | None:
    """Walk up from `start` (default: cwd) looking for the skill's SKILL.md.

    Returns the directory containing SKILL.md, or None if not found within 6 levels.
    The skill checkout is the only place we want to write references/winning-formats.md
    into — we deliberately avoid scribbling on any unrelated checkout.
    """
    cur = (start or Path.cwd()).resolve()
    for _ in range(6):
        if (cur / "SKILL.md").exists() and (cur / "references").is_dir():
            return cur
        if cur.parent == cur:
            return None
        cur = cur.parent
    return None


def _load_threads_metrics(db: DB) -> list[dict[str, Any]]:
    rows = db.conn.execute("""
        SELECT d.content AS title, p.published_at, p.external_id,
               m.views, m.likes, m.comments
        FROM posts p
        JOIN drafts d ON d.id = p.draft_id
        JOIN metrics m ON m.post_id = p.id
        WHERE p.platform = 'threads'
        ORDER BY m.pulled_at DESC
    """).fetchall()

    seen: set[str] = set()
    data: list[dict[str, Any]] = []
    for r in rows:
        if r[2] in seen:
            continue
        seen.add(r[2])
        views = r[3] or 0
        likes = r[4] or 0
        comments = r[5] or 0
        data.append({
            "title": (r[0] or "").strip(),
            "published_at": r[1] or "",
            "views": views,
            "likes": likes,
            "comments": comments,
            "like_rate": round(likes / views * 100, 2) if views else 0.0,
        })
    return data


def _hook_template(title: str) -> str:
    """Classify the opening hook into the same a/b/c/d buckets the prompt uses.

    Heuristic — matches the explicit templates in analysis.py:build_pattern_prompt.
    """
    t = title.lstrip()
    if t.startswith(("有人", "Someone")):
        return "a (Someone-verb)"
    if t.startswith(("你", "Why ", "How ")):
        return "d (Question)"
    if t.startswith("一個") or t.startswith("一家"):
        return "c (Milestone)"
    # Brand-verb: leading token is a known brand or capitalized English word followed by a verb
    first = t.split(" ", 1)[0] if t else ""
    if first and (first[0].isupper() or first in {"Google", "Anthropic", "Perplexity", "Microsoft", "OpenAI", "Meta", "Apple", "Cal.com", "LlamaIndex", "HeyGen", "Hallmark"}):
        return "b (Brand-verb)"
    return "other"


def _short(s: str, n: int) -> str:
    s = s.replace("\n", " ").strip()
    return s if len(s) <= n else s[: n - 1] + "…"


def render_winning_formats(data: list[dict[str, Any]], handle: str = "krumjahn") -> str:
    """Render the markdown report. Pure function — no I/O — for easy testing."""
    if not data:
        return (
            "# Winning Formats — @" + handle + "\n\n"
            "> No synced data yet. Run `orbit sync --platform threads`.\n"
        )

    total_views = sum(d["views"] for d in data)
    total_likes = sum(d["likes"] for d in data)
    total_comments = sum(d["comments"] for d in data)
    avg_views = total_views // len(data)
    avg_like_rate = round(total_likes / total_views * 100, 2) if total_views else 0.0

    top_views = sorted(data, key=lambda d: d["views"], reverse=True)[:10]

    # Hook template breakdown over top-30 (or all if fewer)
    sample = sorted(data, key=lambda d: d["views"], reverse=True)[:30]
    by_hook: dict[str, list[dict[str, Any]]] = {}
    for d in sample:
        by_hook.setdefault(_hook_template(d["title"]), []).append(d)
    hook_lines = []
    for hook, posts in sorted(by_hook.items(), key=lambda kv: -sum(p["views"] for p in kv[1])):
        cnt = len(posts)
        max_v = max(p["views"] for p in posts)
        avg_v = sum(p["views"] for p in posts) // cnt
        hook_lines.append(f"| {hook} | {cnt} | {max_v:,} | {avg_v:,} |")

    # "Make more of this" — above-avg views AND above-avg like rate
    winners = [
        d for d in data
        if d["views"] >= avg_views and d["like_rate"] >= avg_like_rate
    ]
    winners.sort(key=lambda d: d["views"], reverse=True)

    # Dead formats — bottom by views among posts with >0 views
    with_views = [d for d in data if d["views"] > 0]
    dead = sorted(with_views, key=lambda d: d["views"])[:5]

    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines: list[str] = []
    lines.append(f"# Winning Formats — @{handle}")
    lines.append("")
    lines.append(f"> Auto-generated by `orbit sync --platform threads` on {now}.")
    lines.append("> Do not edit by hand — your changes will be overwritten on next sync.")
    lines.append("")
    lines.append(f"## Account Stats (n={len(data)} posts)")
    lines.append("")
    lines.append(f"- Total views: **{total_views:,}**")
    lines.append(f"- Total likes: **{total_likes:,}**")
    lines.append(f"- Total comments: **{total_comments:,}**")
    lines.append(f"- Average views per post: **{avg_views:,}**")
    lines.append(f"- Average like rate: **{avg_like_rate}%**")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## Top 10 by Views")
    lines.append("")
    lines.append("| Rank | Views | Likes | Like % | Hook | Opening |")
    lines.append("|-----:|------:|------:|-------:|------|---------|")
    for i, d in enumerate(top_views, 1):
        lines.append(
            f"| {i} | {d['views']:,} | {d['likes']:,} | {d['like_rate']}% "
            f"| {_hook_template(d['title'])} | {_short(d['title'], 60)} |"
        )
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## Hook Template Performance (top 30 by views)")
    lines.append("")
    lines.append("| Template | Count | Max views | Avg views |")
    lines.append("|----------|------:|----------:|----------:|")
    lines.extend(hook_lines)
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## Make more of this  (above-avg views AND above-avg like rate)")
    lines.append("")
    if winners:
        for d in winners[:15]:
            lines.append(f"- ({d['views']:,} views, {d['like_rate']}%) {_short(d['title'], 80)}")
    else:
        lines.append("_No posts beat both averages yet._")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## Dead formats  (bottom 5 by views — avoid repeating)")
    lines.append("")
    for d in dead:
        lines.append(f"- ({d['views']:,} views) {_short(d['title'], 80)}")
    lines.append("")
    return "\n".join(lines)


def write_winning_formats_for_threads(db: DB, repo_root: Path | None = None) -> Path | None:
    """Render and write `references/winning-formats.md` for Threads.

    Returns the path written, or None if no skill checkout was found in the
    ancestor chain (the user may be running orbit from anywhere — in that
    case the report is a no-op rather than spamming files into cwd).
    """
    root = repo_root if repo_root is not None else find_repo_root()
    if root is None:
        return None
    data = _load_threads_metrics(db)
    out = root / "references" / "winning-formats.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_winning_formats(data), encoding="utf-8")
    return out
